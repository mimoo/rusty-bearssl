const T0_INTERPRETED: u32 = 34;
const INIT_MAIN_SLOT: u32 = 73;

fn init_main(ctx: &mut br_skey_decoder_context) {
    ctx.ip = 0;
    t0_enter(ctx, INIT_MAIN_SLOT);
}

#[inline]
fn t0_enter(ctx: &mut br_skey_decoder_context, slot: u32) {
    let mut newip = T0_CADDR[(slot - T0_INTERPRETED) as usize] as usize;
    let lnum = t0_parse7E_unsigned(&T0_CODEBLOCK, &mut newip);
    ctx.rp += lnum as usize;
    ctx.rp_stack[ctx.rp] = (ctx.ip as u32) + (lnum << 16);
    ctx.rp += 1;
    ctx.ip = newip;
}

macro_rules! pop { ($c:expr) => {{ $c.dp -= 1; $c.dp_stack[$c.dp] }} }
macro_rules! popi { ($c:expr) => {{ $c.dp -= 1; $c.dp_stack[$c.dp] as i32 }} }
macro_rules! push { ($c:expr, $v:expr) => {{ $c.dp_stack[$c.dp] = $v; $c.dp += 1; }} }
macro_rules! pushi { ($c:expr, $v:expr) => {{ $c.dp_stack[$c.dp] = ($v as i32) as u32; $c.dp += 1; }} }
macro_rules! peek { ($c:expr, $x:expr) => {{ $c.dp_stack[$c.dp - 1 - ($x)] }} }
macro_rules! local { ($c:expr, $x:expr) => { $c.rp_stack[$c.rp - 2 - ($x as usize)] } }

/// Faithful port of `br_skey_decoder_run`.
fn run(ctx: &mut br_skey_decoder_context, chunk: &[u8]) {
    let mut t0x: u32;
    loop {
        t0x = T0_CODEBLOCK[ctx.ip] as u32;
        ctx.ip += 1;
        if t0x < T0_INTERPRETED {
            match t0x {
                0 => {
                    ctx.rp -= 1;
                    let v = ctx.rp_stack[ctx.rp];
                    ctx.rp -= (v >> 16) as usize;
                    let v = v & 0xFFFF;
                    if v == 0 {
                        return;
                    }
                    ctx.ip = v as usize;
                }
                1 => {
                    let v = t0_parse7E_signed(&T0_CODEBLOCK, &mut ctx.ip);
                    pushi!(ctx, v);
                }
                2 => {
                    let x = t0_parse7E_unsigned(&T0_CODEBLOCK, &mut ctx.ip);
                    let v = local!(ctx, x);
                    push!(ctx, v);
                }
                3 => {
                    let x = t0_parse7E_unsigned(&T0_CODEBLOCK, &mut ctx.ip);
                    let v = pop!(ctx);
                    local!(ctx, x) = v;
                }
                4 => {
                    let off = t0_parse7E_signed(&T0_CODEBLOCK, &mut ctx.ip);
                    ctx.ip = (ctx.ip as i32 + off) as usize;
                }
                5 => {
                    let off = t0_parse7E_signed(&T0_CODEBLOCK, &mut ctx.ip);
                    if pop!(ctx) != 0 {
                        ctx.ip = (ctx.ip as i32 + off) as usize;
                    }
                }
                6 => {
                    let off = t0_parse7E_signed(&T0_CODEBLOCK, &mut ctx.ip);
                    if pop!(ctx) == 0 {
                        ctx.ip = (ctx.ip as i32 + off) as usize;
                    }
                }
                7 => {
                    // +
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, a.wrapping_add(b));
                }
                8 => {
                    // -
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, a.wrapping_sub(b));
                }
                9 => {
                    // -rot
                    let t = pop!(ctx);
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, t);
                    push!(ctx, a);
                    push!(ctx, b);
                }
                10 => {
                    // <
                    let b = popi!(ctx);
                    let a = popi!(ctx);
                    push!(ctx, (0u32).wrapping_sub((a < b) as u32));
                }
                11 => {
                    // <<
                    let c = popi!(ctx);
                    let x = pop!(ctx);
                    push!(ctx, x.wrapping_shl(c as u32));
                }
                12 => {
                    // <>
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, (0u32).wrapping_sub((a != b) as u32));
                }
                13 => {
                    // =
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, (0u32).wrapping_sub((a == b) as u32));
                }
                14 => {
                    // >
                    let b = popi!(ctx);
                    let a = popi!(ctx);
                    push!(ctx, (0u32).wrapping_sub((a > b) as u32));
                }
                15 => {
                    // >=
                    let b = popi!(ctx);
                    let a = popi!(ctx);
                    push!(ctx, (0u32).wrapping_sub((a >= b) as u32));
                }
                16 => {
                    // >>
                    let c = popi!(ctx);
                    let x = popi!(ctx);
                    pushi!(ctx, x >> c);
                }
                17 => {
                    // and
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, a & b);
                }
                18 => {
                    // co
                    return;
                }
                19 => {
                    // drop
                    let _ = pop!(ctx);
                }
                20 => {
                    // dup
                    let v = peek!(ctx, 0);
                    push!(ctx, v);
                }
                21 => {
                    // eqOID
                    let a2 = pop!(ctx) as usize;
                    let len = ctx.mem[OFF_PAD as usize] as usize;
                    let x: i32;
                    if len == T0_DATABLOCK[a2] as usize {
                        let eq = ctx.mem[OFF_PAD as usize + 1..OFF_PAD as usize + 1 + len]
                            == T0_DATABLOCK[a2 + 1..a2 + 1 + len];
                        x = -(eq as i32);
                    } else {
                        x = 0;
                    }
                    push!(ctx, x as u32);
                }
                22 => {
                    // fail
                    ctx.err = popi!(ctx);
                    return;
                }
                23 => {
                    // get8
                    let addr = pop!(ctx);
                    push!(ctx, ctx.get8(addr) as u32);
                }
                24 => {
                    // neg
                    let a = pop!(ctx);
                    push!(ctx, a.wrapping_neg());
                }
                25 => {
                    // over
                    let v = peek!(ctx, 1);
                    push!(ctx, v);
                }
                26 => {
                    // read-blob-inner
                    let len = pop!(ctx);
                    let addr = pop!(ctx);
                    let mut clen = ctx.hlen;
                    if clen > len as usize {
                        clen = len as usize;
                    }
                    if addr != 0 {
                        ctx.mem[addr as usize..addr as usize + clen]
                            .copy_from_slice(&chunk[ctx.cur_pos..ctx.cur_pos + clen]);
                    }
                    ctx.cur_pos += clen;
                    ctx.hlen -= clen;
                    push!(ctx, addr + clen as u32);
                    push!(ctx, len - clen as u32);
                }
                27 => {
                    // read8-low
                    if ctx.hlen == 0 {
                        pushi!(ctx, -1);
                    } else {
                        ctx.hlen -= 1;
                        let x = chunk[ctx.cur_pos];
                        ctx.cur_pos += 1;
                        push!(ctx, x as u32);
                    }
                }
                28 => {
                    // rot
                    let c = pop!(ctx);
                    let b = pop!(ctx);
                    let a = pop!(ctx);
                    push!(ctx, b);
                    push!(ctx, c);
                    push!(ctx, a);
                }
                29 => {
                    // set-ec-key
                    let xlen = pop!(ctx) as usize;
                    let curve = pop!(ctx) as i32;
                    let base = OFF_KEY_DATA as usize;
                    let x = ctx.mem[base..base + xlen].to_vec();
                    ctx.key = br_skey::EC { curve, x };
                }
                30 => {
                    // set-rsa-key
                    let iqlen = pop!(ctx) as usize;
                    let dqlen = pop!(ctx) as usize;
                    let dplen = pop!(ctx) as usize;
                    let qlen = pop!(ctx) as usize;
                    let plen = pop!(ctx) as usize;
                    let n_bitlen = pop!(ctx);
                    let base = OFF_KEY_DATA as usize;
                    let mut off = 0usize;
                    let p = ctx.mem[base + off..base + off + plen].to_vec();
                    off += plen;
                    let q = ctx.mem[base + off..base + off + qlen].to_vec();
                    off += qlen;
                    let dp = ctx.mem[base + off..base + off + dplen].to_vec();
                    off += dplen;
                    let dq = ctx.mem[base + off..base + off + dqlen].to_vec();
                    off += dqlen;
                    let iq = ctx.mem[base + off..base + off + iqlen].to_vec();
                    ctx.key = br_skey::RSA {
                        n_bitlen,
                        p,
                        q,
                        dp,
                        dq,
                        iq,
                    };
                }
                31 => {
                    // set8
                    let addr = pop!(ctx);
                    let v = pop!(ctx);
                    ctx.set8(addr, v as u8);
                }
                32 => {
                    // swap
                    let t = ctx.dp_stack[ctx.dp - 2];
                    ctx.dp_stack[ctx.dp - 2] = ctx.dp_stack[ctx.dp - 1];
                    ctx.dp_stack[ctx.dp - 1] = t;
                }
                33 => {
                    // u>>
                    let c = popi!(ctx);
                    let x = pop!(ctx);
                    push!(ctx, x >> c);
                }
                _ => unreachable!(),
            }
        } else {
            t0_enter(ctx, t0x);
        }
    }
}
