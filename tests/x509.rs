fn hex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

#[test]
fn decode_ec_certificate_pubkey() {
    let mut ctx = br_x509_decoder_init(None);
    br_x509_decoder_push(&mut ctx, EE_P256_DER);
    assert_eq!(ctx.last_error(), 0, "decoding should succeed");
    let pk = ctx.get_pkey().expect("pkey present");
    match pk {
        br_x509_pkey::EC { curve, q } => {
            assert_eq!(*curve, bearssl::ec::BR_EC_secp256r1);
            let expected = hex("045f389da7ff4d8aaff63439461afc3adff423aaa9eafbc508de008ebe79a537584c6ddd01caab47df89b6c7171f38fc1d2014dd45c0e08f934e380bfce999a149");
            assert_eq!(q, &expected, "EC point mismatch");
        }
        _ => panic!("expected EC key, got {:?}", pk.key_type()),
    }
    // The EE cert is signed by an EC (P-256) CA with SHA-256.
    assert_eq!(ctx.signer_key_type(), BR_KEYTYPE_EC);
}

#[test]
fn decode_subject_dn_via_callback() {
    let mut collected: Vec<u8> = Vec::new();
    {
        let mut sink = |b: &[u8]| collected.extend_from_slice(b);
        let mut ctx = br_x509_decoder_init(Some(&mut sink));
        br_x509_decoder_push(&mut ctx, EE_P256_DER);
        assert_eq!(ctx.last_error(), 0);
    }
    // The subject DN is a non-empty DER SEQUENCE.
    assert!(!collected.is_empty());
    assert_eq!(collected[0], 0x30, "DN should be a DER SEQUENCE");
}

