// Validation date inside the certificates' validity window (2020-06-15 UTC).
const VALID_DAYS: u32 = 737956;
const VALID_SECONDS: u32 = 0;

fn full_init<'a>(
    anchors: &'a [br_x509_trust_anchor<'a>],
) -> br_x509_minimal_context<'a> {
    let mut ctx = br_x509_minimal_init(&br_sha256_vtable, anchors);
    ctx.set_rsa(br_rsa_i31_pkcs1_vrfy);
    ctx.set_ecdsa(br_ec_get_default(), br_ecdsa_i31_vrfy_asn1);
    ctx.set_hash(1, Some(&br_md5_vtable));
    ctx.set_hash(2, Some(&br_sha1_vtable));
    ctx.set_hash(3, Some(&br_sha224_vtable));
    ctx.set_hash(4, Some(&br_sha256_vtable));
    ctx.set_hash(5, Some(&br_sha384_vtable));
    ctx.set_hash(6, Some(&br_sha512_vtable));
    ctx.set_time(VALID_DAYS, VALID_SECONDS);
    ctx
}

fn run_chain(ctx: &mut dyn X509Engine, certs: &[&[u8]]) -> u32 {
    ctx.start_chain(None);
    for c in certs {
        ctx.start_cert(c.len() as u32);
        ctx.append(c);
        ctx.end_cert();
    }
    ctx.end_chain()
}

#[test]
fn minimal_validates_good_rsa_chain() {
    let n = hex(ROOT_RSA_N);
    let e = hex("010001");
    let anchors = [br_x509_trust_anchor {
        dn: DN_ROOT,
        flags: BR_X509_TA_CA,
        pkey: br_x509_pkey::RSA { n: n.clone(), e: e.clone() },
    }];
    let mut ctx = full_init(&anchors);
    ctx.set_server_name(Some("www.example.com"));
    let err = run_chain(&mut ctx, &[EE_CRT, ICA2_CRT, ICA1_CRT]);
    assert_eq!(err, 0, "good chain should validate (got err {})", err);

    let mut usages = 0u32;
    let pk = ctx.get_pkey(Some(&mut usages)).expect("EE pkey");
    assert_eq!(pk.key_type(), BR_KEYTYPE_RSA);
}

