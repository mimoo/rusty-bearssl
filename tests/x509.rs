// Root with an ECDSA P-256 key (root-p256 from alltests.txt), CA.
const ROOT_P256_Q: &str = "047174BAABB9302E81D5E557F9F320680C9CF964DBB4200D6DEA40D04A6E42FDB69A682544F6DF7BC4FCDEDD7BBBC5DB7C763F4166406EDBA787C2E5D8C5F37F8D";

#[test]
fn minimal_validates_good_ec_chain() {
    let q = hex(ROOT_P256_Q);
    let anchors = [br_x509_trust_anchor {
        dn: DN_ROOT,
        flags: BR_X509_TA_CA,
        pkey: br_x509_pkey::EC { curve: bearssl::ec::BR_EC_secp256r1, q },
    }];
    let mut ctx = full_init(&anchors);
    ctx.set_server_name(Some("www.example.com"));
    let err = run_chain(&mut ctx, &[EE_P256_DER, ICA2_P256_CRT, ICA1_P256_CRT]);
    assert_eq!(err, 0, "good EC chain should validate (got {})", err);
    let pk = ctx.get_pkey(None).expect("EE pkey");
    assert_eq!(pk.key_type(), BR_KEYTYPE_EC);
}

#[test]
fn minimal_rejects_tampered_ee_signature() {
    // Flip a byte in the EE certificate body: the signature over its TBS no
    // longer verifies against the issuer (ICA2) key.
    let mut bad = EE_CRT.to_vec();
    let mid = bad.len() / 2;
    bad[mid] ^= 0xFF;
    let n = hex(ROOT_RSA_N);
    let e = hex("010001");
    let anchors = [br_x509_trust_anchor {
        dn: DN_ROOT,
        flags: BR_X509_TA_CA,
        pkey: br_x509_pkey::RSA { n, e },
    }];
    let mut ctx = full_init(&anchors);
    ctx.set_server_name(Some("www.example.com"));
    let err = run_chain(&mut ctx, &[&bad, ICA2_CRT, ICA1_CRT]);
    assert_ne!(err, 0, "tampered chain must not validate");
}
