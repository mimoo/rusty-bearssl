// ---- DER encode helper ------------------------------------------------------

fn encode<F: Fn(Option<&mut [u8]>) -> usize>(f: F) -> Vec<u8> {
    let len = f(None);
    assert!(len > 0, "encoder returned 0 length");
    let mut out = vec![0u8; len];
    let n = f(Some(&mut out));
    assert_eq!(n, len);
    out
}

// ---- tests ------------------------------------------------------------------

#[test]
fn rsa_raw_der_roundtrip() {
    let sk = rsa_sk();
    let pk = rsa_pk();
    let der = encode(|d| br_encode_rsa_raw_der(d, &sk, &pk, RSA_D));
    assert_eq!(der[0], 0x30, "RSAPrivateKey must start with SEQUENCE");
    assert_rsa_roundtrip(&der);
}

#[test]
fn rsa_pkcs8_der_roundtrip() {
    let sk = rsa_sk();
    let pk = rsa_pk();
    let der = encode(|d| br_encode_rsa_pkcs8_der(d, &sk, &pk, RSA_D));
    assert_eq!(der[0], 0x30);
    assert_rsa_roundtrip(&der);
}

#[test]
fn ec_raw_der_roundtrip() {
    let sk = ec_sk();
    let pk = ec_pk();
    let der = encode(|d| br_encode_ec_raw_der(d, &sk, Some(&pk)));
    assert_eq!(der[0], 0x30, "ECPrivateKey must start with SEQUENCE");
    assert_ec_roundtrip(&der);

    // Without the public key, the round-trip must still recover the scalar.
    let der_nopub = encode(|d| br_encode_ec_raw_der(d, &sk, None));
    assert_ec_roundtrip(&der_nopub);
}

#[test]
fn ec_pkcs8_der_roundtrip() {
    let sk = ec_sk();
    let pk = ec_pk();
    let der = encode(|d| br_encode_ec_pkcs8_der(d, &sk, Some(&pk)));
    assert_eq!(der[0], 0x30);
    assert_ec_roundtrip(&der);
}

#[test]
fn pem_roundtrip_single() {
    // Encode an arbitrary DER blob, decode it back, assert the bytes match.
    let sk = rsa_sk();
    let pk = rsa_pk();
    let der = encode(|d| br_encode_rsa_pkcs8_der(d, &sk, &pk, RSA_D));

    let pem = pem_encode(&der, "PRIVATE KEY", 0);
    // Banner sanity.
    let text = std::str::from_utf8(&pem).unwrap();
    assert!(text.starts_with("-----BEGIN PRIVATE KEY-----\n"));
    assert!(text.trim_end().ends_with("-----END PRIVATE KEY-----"));

    let objs = pem_decode_all(&pem);
    assert_eq!(objs.len(), 1);
    assert_eq!(objs[0].0, "PRIVATE KEY");
    assert_eq!(objs[0].1, der);
}

#[test]
fn pem_roundtrip_multi() {
    let sk = rsa_sk();
    let pk = rsa_pk();
    let der_rsa = encode(|d| br_encode_rsa_pkcs8_der(d, &sk, &pk, RSA_D));
    let esk = ec_sk();
    let epk = ec_pk();
    let der_ec = encode(|d| br_encode_ec_pkcs8_der(d, &esk, Some(&epk)));

    let mut blob = pem_encode(&der_rsa, "RSA TEST", BR_PEM_LINE64);
    blob.extend_from_slice(&pem_encode(&der_ec, "EC TEST", 0));

    let objs = pem_decode_all(&blob);
    assert_eq!(objs.len(), 2);
    assert_eq!(objs[0].0, "RSA TEST");
    assert_eq!(objs[0].1, der_rsa);
    assert_eq!(objs[1].0, "EC TEST");
    assert_eq!(objs[1].1, der_ec);
}

/// Cross-check banner and Base64 line wrapping against a real PEM certificate
/// from BearSSL's samples: decode it, re-encode with the same (default, 76-col,
/// LF) settings, and require an exact byte match.
#[test]
fn pem_known_cert_byte_exact() {
    const CERT_PEM: &str =
        include_str!("../../BearSSL/samples/cert-ee-rsa.pem");
    let pem = CERT_PEM.as_bytes();

    let objs = pem_decode_all(pem);
    assert_eq!(objs.len(), 1);
    assert_eq!(objs[0].0, "CERTIFICATE");

    let reencoded = pem_encode(&objs[0].1, "CERTIFICATE", 0);
    assert_eq!(
        std::str::from_utf8(&reencoded).unwrap(),
        CERT_PEM,
        "re-encoded PEM must byte-match the original sample"
    );
}
