fn assert_rsa_roundtrip(der: &[u8]) {
    let mut dc = br_skey_decoder_init();
    br_skey_decoder_push(&mut dc, der);
    assert_eq!(dc.last_error(), 0, "skey decode error");
    match dc.key() {
        br_skey::RSA {
            n_bitlen,
            p,
            q,
            dp,
            dq,
            iq,
        } => {
            assert_eq!(*n_bitlen, 1028);
            assert_eq!(norm(p), norm(RSA_P));
            assert_eq!(norm(q), norm(RSA_Q));
            assert_eq!(norm(dp), norm(RSA_DP));
            assert_eq!(norm(dq), norm(RSA_DQ));
            assert_eq!(norm(iq), norm(RSA_IQ));
        }
        other => panic!("expected RSA key, got {other:?}"),
    }
}

