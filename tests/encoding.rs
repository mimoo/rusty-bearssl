//! PEM codec and DER key-encoding round-trip tests.
//!
//! Covers `br_pem_encode` / `br_pem_decoder_*` and the four DER key encoders
//! (`br_encode_rsa_raw_der`, `br_encode_rsa_pkcs8_der`, `br_encode_ec_raw_der`,
//! `br_encode_ec_pkcs8_der`). Encoded keys are decoded back with the ported
//! `br_skey_decoder` and their fields are compared; the PEM line-wrapping and
//! banner are cross-checked against a real certificate from BearSSL's samples.

use bearssl::codec::{
    br_pem_decoder_event, br_pem_decoder_init, br_pem_decoder_push, br_pem_decoder_setdest,
    br_pem_encode, BR_PEM_BEGIN_OBJ, BR_PEM_END_OBJ, BR_PEM_LINE64,
};
use bearssl::ec::{br_ec_private_key, br_ec_public_key, BR_EC_secp256r1};
use bearssl::rsa::{br_rsa_private_key, br_rsa_public_key};
use bearssl::x509::{
    br_encode_ec_pkcs8_der, br_encode_ec_raw_der, br_encode_rsa_pkcs8_der,
    br_encode_rsa_raw_der, br_skey, br_skey_decoder_init, br_skey_decoder_push,
};

// ---- helpers ----------------------------------------------------------------

/// Encode `data` to PEM, returning the produced bytes (without the final NUL).
fn pem_encode(data: &[u8], banner: &str, flags: u32) -> Vec<u8> {
    let dlen = br_pem_encode(None, data, data.len(), banner, flags);
    let mut out = vec![0u8; dlen + 1];
    let n = br_pem_encode(Some(&mut out), data, data.len(), banner, flags);
    assert_eq!(n, dlen);
    out.truncate(dlen);
    out
}

/// Decode a complete PEM text, returning (object name, decoded bytes) per
/// object encountered.
///
/// The decoder's `dest` callback accumulates into a shared buffer; the main
/// loop snapshots that buffer (and the current object name) at each END event.
fn pem_decode_all(pem: &[u8]) -> Vec<(String, Vec<u8>)> {
    use std::cell::RefCell;
    use std::rc::Rc;

    let mut objects: Vec<(String, Vec<u8>)> = Vec::new();
    let collected: Rc<RefCell<Vec<u8>>> = Rc::new(RefCell::new(Vec::new()));

    // A single, persistent receiver installed for the whole decode run.
    let sink = collected.clone();
    let mut cb = move |chunk: &[u8]| sink.borrow_mut().extend_from_slice(chunk);

    let mut ctx = br_pem_decoder_init();
    br_pem_decoder_setdest(&mut ctx, Some(&mut cb));

    let mut pos = 0usize;
    let mut pending_name: Option<String> = None;

    loop {
        let consumed = br_pem_decoder_push(&mut ctx, &pem[pos..]);
        pos += consumed;
        match br_pem_decoder_event(&mut ctx) {
            BR_PEM_BEGIN_OBJ => {
                pending_name = Some(ctx.name().to_string());
                collected.borrow_mut().clear();
            }
            BR_PEM_END_OBJ => {
                let name = pending_name.take().unwrap_or_default();
                objects.push((name, collected.borrow().clone()));
            }
            0 => {
                // No event: either we consumed everything, or the decoder is
                // waiting for more bytes that we don't have.
                if pos >= pem.len() {
                    break;
                }
                if consumed == 0 {
                    break;
                }
            }
            ev => panic!("unexpected PEM event {ev}"),
        }
    }
    objects
}

fn norm(v: &[u8]) -> &[u8] {
    let mut i = 0;
    while i + 1 < v.len() && v[i] == 0 {
        i += 1;
    }
    &v[i..]
}

